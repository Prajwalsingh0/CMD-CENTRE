-- AI Command Center :: refresh tokens
-- Portable SQL: runs on H2 (MODE=PostgreSQL) and on PostgreSQL.
--
-- Only the SHA-256 hash of a refresh token is stored, never the token itself: a database
-- reader cannot turn a row back into a usable credential. Rows are grouped into a family so
-- that rotating one token can invalidate its whole chain when a reused token is detected.

CREATE TABLE refresh_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL,
    token_hash   VARCHAR(64) NOT NULL,
    family_id    VARCHAR(36) NOT NULL,
    expires_at   TIMESTAMP NOT NULL,
    revoked_at   TIMESTAMP,
    replaced_by  VARCHAR(64),
    created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_refresh_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_refresh_hash UNIQUE (token_hash)
);

CREATE INDEX ix_refresh_user ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_family ON refresh_tokens (family_id);
